//! Shared helpers for checks that run the pinned npm tools (oxfmt, oxlint, tsc, stylelint).
//!
//! The tools come from the root `package.json` / `package-lock.json` and live in
//! `node_modules/.bin` of the work folder (ADR-0014, ADR-0024). `npm ci` installs them.

use std::fs;
use std::path::Path;
use std::process::Command;

use anyhow::{Context as _, bail};

use super::{Context, Finding};

/// Folders that never hold our sources.
const SKIPPED_FOLDERS: [&str; 6] = [
    "node_modules",
    "target",
    "dist",
    ".git",
    ".tools",
    ".claude",
];

/// Check examples live here; the normal runs of the checks must not see them.
const FIXTURES_FOLDER: &str = "tools/checks/fixtures";

/// Files that are generated by npm and never formatted by us.
const LOCK_FILE: &str = "package-lock.json";

/// What a tool printed and whether it succeeded.
pub(crate) struct ToolRun {
    pub(crate) success: bool,
    pub(crate) output: String,
}

/// Runs `node_modules/.bin/<tool>` in `root`.
pub(crate) fn run(root: &Path, tool: &str, args: &[&str]) -> anyhow::Result<ToolRun> {
    let name = if cfg!(windows) {
        format!("{tool}.cmd")
    } else {
        tool.to_owned()
    };
    let binary = root.join("node_modules").join(".bin").join(name);
    if !binary.exists() {
        bail!(
            "`{tool}` is not installed. Run `npm ci` in {} first.",
            root.display()
        );
    }
    let out = Command::new(&binary)
        .args(args)
        .current_dir(root)
        .output()
        .with_context(|| format!("could not start {}", binary.display()))?;
    let mut output = String::from_utf8_lossy(&out.stdout).into_owned();
    output.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok(ToolRun {
        success: out.status.success(),
        output,
    })
}

/// The files of a check: where to look and which endings count.
pub(crate) struct Selection {
    /// Folders to search, relative to the root. `""` is the whole repository, `"."` only the
    /// files directly in the root.
    pub(crate) folders: &'static [&'static str],
    /// Single files outside those folders, relative to the root.
    pub(crate) files: &'static [&'static str],
    pub(crate) endings: &'static [&'static str],
}

impl Selection {
    fn wants(&self, path: &str) -> bool {
        if path.starts_with(FIXTURES_FOLDER)
            || path.ends_with(LOCK_FILE)
            || path.split('/').any(|part| SKIPPED_FOLDERS.contains(&part))
        {
            return false;
        }
        if self.files.contains(&path) {
            return true;
        }
        let in_folder = self.folders.iter().any(|folder| {
            folder.is_empty()
                || (*folder == "." && !path.contains('/'))
                || path
                    .strip_prefix(folder)
                    .is_some_and(|rest| rest.starts_with('/'))
        });
        in_folder && self.endings.iter().any(|ending| path.ends_with(ending))
    }

    /// The files this run is about: the edited files that qualify, or everything that qualifies.
    pub(crate) fn pick(&self, context: &Context<'_>) -> Vec<String> {
        let root = context.repo.root();
        let mut picked: Vec<String> = Vec::new();
        if let Some(changed) = context.files {
            picked.extend(
                changed
                    .iter()
                    .filter(|path| self.wants(path) && root.join(path).is_file())
                    .cloned(),
            );
        } else {
            for folder in self.folders {
                if *folder == "." {
                    root_files(root, &mut picked);
                } else {
                    walk(root, &root.join(folder), &mut picked);
                }
            }
            picked.retain(|path| self.wants(path));
            picked.extend(
                self.files
                    .iter()
                    .filter(|file| root.join(file).is_file())
                    .map(|file| (*file).to_owned()),
            );
        }
        picked.sort();
        picked.dedup();
        picked
    }
}

/// The files directly in the repository root.
fn root_files(root: &Path, found: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(root) else {
        return;
    };
    for entry in entries.flatten() {
        if entry.path().is_file() {
            found.push(entry.file_name().to_string_lossy().into_owned());
        }
    }
}

fn walk(root: &Path, folder: &Path, found: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(folder) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        if path.is_dir() {
            if !SKIPPED_FOLDERS.contains(&name.to_string_lossy().as_ref()) {
                walk(root, &path, found);
            }
        } else if let Ok(relative) = path.strip_prefix(root) {
            found.push(relative.to_string_lossy().replace('\\', "/"));
        }
    }
}

/// Turns `file:line:col: message [rule]` lines (oxlint and stylelint `unix` format) into findings.
pub(crate) fn unix_findings(run: &ToolRun) -> Vec<Finding> {
    let mut findings: Vec<Finding> = run.output.lines().filter_map(parse_unix_line).collect();
    if findings.is_empty() && !run.success {
        findings.push(Finding::general(format!(
            "The tool failed without naming a problem:\n{}",
            run.output.trim()
        )));
    }
    findings
}

fn parse_unix_line(line: &str) -> Option<Finding> {
    for (index, _) in line.match_indices(':') {
        let after = &line[index + 1..];
        let Some((row, after_row)) = take_digits(after) else {
            continue;
        };
        let Some((_, message)) = after_row
            .strip_prefix(':')
            .and_then(take_digits)
            .and_then(|(column, rest)| rest.strip_prefix(':').map(|rest| (column, rest)))
        else {
            continue;
        };
        return Some(Finding::at(
            format!("{}:{row}", &line[..index]),
            message.trim().to_owned(),
        ));
    }
    None
}

fn take_digits(text: &str) -> Option<(&str, &str)> {
    let end = text
        .find(|c: char| !c.is_ascii_digit())
        .unwrap_or(text.len());
    (end > 0).then(|| text.split_at(end))
}

/// Runs oxfmt in check mode and reports every file that is not formatted.
pub(crate) fn unformatted(root: &Path, files: &[String]) -> anyhow::Result<Vec<Finding>> {
    if files.is_empty() {
        return Ok(Vec::new());
    }
    let mut args = vec!["--list-different", "--config", ".oxfmtrc.json"];
    args.extend(files.iter().map(String::as_str));
    let result = run(root, "oxfmt", &args)?;
    let mut findings: Vec<Finding> = result
        .output
        .lines()
        .map(|line| line.trim().replace(std::path::MAIN_SEPARATOR, "/"))
        .filter(|line| files.contains(line))
        .map(|line| {
            Finding::at(
                line,
                "Not formatted. Run `npx oxfmt --config .oxfmtrc.json <file>` to fix it.",
            )
        })
        .collect();
    if findings.is_empty() && !result.success {
        findings.push(Finding::general(format!(
            "oxfmt failed:\n{}",
            result.output.trim()
        )));
    }
    Ok(findings)
}
