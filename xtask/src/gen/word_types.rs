//! `cargo xtask gen word-types`: the TypeScript types of what `bb-wasm` takes and gives, from the
//! Rust types of the wording and of the readability of an own theme in `bb-core` (coding-standards
//! section 1).
//!
//! The browser sends a change or a notification to the module as JSON and reads `Said` back. The
//! Rust structs are the one declaration; `web/packages/wasm/src/wording.generated.ts` is written
//! from them with the same reader as the book of a load run (`ts_types.rs`), and DOC-GENERATED
//! fails when the file is not what the structs give.

use anyhow::Context as _;

use super::Generated;
use super::api::format_with_oxfmt;
use super::ts_types::{generated_file, types_under};
use crate::repo::Repo;
use crate::source::read_text;

/// The generated file, relative to the repository root.
pub(crate) const OUTPUT: &str = "web/packages/wasm/src/wording.generated.ts";
/// The Rust types it is made from.
const SOURCE: &str = "crates/bb-core/src/wording/mod.rs";
const HEADER: &str = "// Generated by `cargo xtask gen word-types`. Do not edit by hand.\n\nimport type { Schema } from \"@bugaboo/api-client\";\n\n";

/// The generated file of the readability of an own theme, relative to the repository root.
pub(crate) const READABILITY_OUTPUT: &str = "web/packages/wasm/src/readability.generated.ts";
/// The Rust types it is made from: the rating of a pair, then the pairs, the sums and the colors
/// that the theme editor is told about.
const READABILITY_SOURCES: [&str; 2] = [
    "crates/bb-core/src/contrast/rating.rs",
    "crates/bb-core/src/theme/colors.rs",
];
const READABILITY_HEADER: &str =
    "// Generated by `cargo xtask gen word-types`. Do not edit by hand.\n\n";

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    let mut files = generated_file(repo, OUTPUT, SOURCE, HEADER)?;
    files.push(Generated::new(
        READABILITY_OUTPUT,
        format_with_oxfmt(repo, READABILITY_OUTPUT, &readability_types(repo)?)?,
    ));
    Ok(files)
}

/// The types of the readability, from its sources read as one: the inner doc comments of each file
/// are left out, so they can follow each other.
fn readability_types(repo: &Repo) -> anyhow::Result<String> {
    let mut source = String::new();
    for path in READABILITY_SOURCES {
        for line in read_text(repo, path)?.lines() {
            if !line.starts_with("//!") {
                source.push_str(line);
                source.push('\n');
            }
        }
    }
    types_under(&source, READABILITY_HEADER)
        .context("the readability of an own theme cannot be written as types")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generate::ts_types::types_under;

    #[test]
    fn the_wording_can_be_written_as_types() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap_or(std::path::Path::new("."));
        let source = std::fs::read_to_string(root.join(SOURCE)).unwrap_or_default();
        let text = types_under(&source, HEADER).unwrap_or_default();
        for expected in [
            "export type Said =",
            "export type Side =",
            "readonly shown: \"text\";",
            "readonly kind: Schema<\"FieldType\">;",
            "export interface Notice {",
            "readonly kind: Schema<\"NotificationKind\">;",
            "readonly changes?: readonly Change[];",
            "readonly args: Readonly<Record<string, Said>>;",
        ] {
            assert!(text.contains(expected), "{expected}: {text}");
        }
    }
}
