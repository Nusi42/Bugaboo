//! `cargo xtask gen word-types`: the TypeScript types of what `bb-wasm` takes and gives, from the
//! Rust types of the wording in `bb-core` (coding-standards section 1).
//!
//! The browser sends a change or a notification to the module as JSON and reads `Said` back. The
//! Rust structs are the one declaration; `web/packages/wasm/src/wording.generated.ts` is written
//! from them with the same reader as the book of a load run (`load_book.rs`), and DOC-GENERATED
//! fails when the file is not what the structs give.

use anyhow::Context as _;

use super::Generated;
use super::api::format_with_oxfmt;
use super::load_book::types_under;
use crate::repo::Repo;
use crate::source::read_text;

/// The generated file, relative to the repository root.
pub(crate) const OUTPUT: &str = "web/packages/wasm/src/wording.generated.ts";
/// The Rust types it is made from.
const SOURCE: &str = "crates/bb-core/src/wording/mod.rs";
const HEADER: &str = "// Generated by `cargo xtask gen word-types`. Do not edit by hand.\n\nimport type { Schema } from \"@bugaboo/api-client\";\n\n";

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    let source = read_text(repo, SOURCE)?;
    let text = types_under(&source, HEADER)
        .with_context(|| format!("{SOURCE} cannot be written as types"))?;
    Ok(vec![Generated::new(
        OUTPUT,
        format_with_oxfmt(repo, OUTPUT, &text)?,
    )])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_wording_can_be_written_as_types() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap_or(std::path::Path::new("."));
        let source = std::fs::read_to_string(root.join(SOURCE)).unwrap_or_default();
        let text = types_under(&source, HEADER).unwrap_or_default();
        for expected in [
            "export type Said =",
            "export type Side =",
            "readonly shown: \"text\";",
            "readonly kind: Schema<\"FieldType\">;",
            "export interface Notice {",
            "readonly kind: Schema<\"NotificationKind\">;",
            "readonly changes?: readonly Change[];",
            "readonly args: Readonly<Record<string, Said>>;",
        ] {
            assert!(text.contains(expected), "{expected}: {text}");
        }
    }
}
