//! The user pages whose numbers come from the code (M4-F82, M5 WP-10), so a page never writes a
//! number a second time: the limits of a search (`userDocs/issues/search-limits.md`) and the times
//! and counts of notifications, e-mail, signing up and handles (`userDocs/notifications/numbers.md`).
//! The numbers are read from the Rust source like those of the constants for the browser.

use std::fmt::Write as _;

use anyhow::{Context as _, bail};

use super::notifications::{
    HANDLE_SOURCE, MAIL_SOURCE, NOTIFICATION_SOURCE, SIGN_UP_SOURCE, parsed as parsed_file,
};
use super::number_const;
use crate::generate::privacy::table;
use crate::source::Source;

/// The user page about the limits of a search.
pub(crate) const SEARCH_LIMITS_PAGE: &str = "userDocs/issues/search-limits.md";
/// The user page about the times and counts of notifications.
pub(crate) const NOTIFICATION_NUMBERS_PAGE: &str = "userDocs/notifications/numbers.md";

const LIMITS_SOURCE: &str = "crates/bb-searchlang/src/limits.rs";
const WORDS_SOURCE: &str = "crates/bb-core/src/text_words.rs";

/// What a generated page says first.
fn header(title: &str) -> String {
    format!(
        "# {title}\n\nGENERATED by `cargo xtask gen api` from the numbers in the code. Do not edit this page by hand.\n\n"
    )
}

/// A number of the code, as a whole number.
fn number(sources: &[Source], path: &str, name: &str) -> anyhow::Result<u128> {
    let text = number_const(&parsed_file(sources, path)?, path, name)?;
    text.parse()
        .with_context(|| format!("{path}: `{name}` is {text}, not a whole number"))
}

/// `count` of a thing, in the singular for one.
fn counted(count: u128, one: &str, many: &str) -> String {
    format!("{count} {}", if count == 1 { one } else { many })
}

/// The limits of a search, in plain words.
fn search_limits(sources: &[Source]) -> anyhow::Result<String> {
    let limit = |name: &str| number(sources, LIMITS_SOURCE, name);
    let word = |name: &str| number(sources, WORDS_SOURCE, name);
    let rows = vec![
        vec![
            "Filters in one search".to_owned(),
            limit("MAX_FILTERS")?.to_string(),
            "`in (a, b, c)` counts as many filters as it has values.".to_owned(),
        ],
        vec![
            "Words in one `contains`".to_owned(),
            limit("MAX_CONTAINS_WORDS")?.to_string(),
            "A word that comes twice counts once.".to_owned(),
        ],
        vec![
            "Keys of `sort by`".to_owned(),
            limit("MAX_SORT_KEYS")?.to_string(),
            String::new(),
        ],
        vec![
            "Steps of `connected to … within N steps`".to_owned(),
            limit("MAX_STEPS")?.to_string(),
            String::new(),
        ],
        vec![
            "Brackets inside brackets".to_owned(),
            limit("MAX_DEPTH")?.to_string(),
            "`not` counts like a bracket.".to_owned(),
        ],
        vec![
            "Length of the text of a search".to_owned(),
            counted(limit("MAX_TEXT_BYTES")?, "byte", "bytes"),
            "Letters with accents and other scripts take more than one byte.".to_owned(),
        ],
        vec![
            "Longest word that is looked for".to_owned(),
            counted(word("MAX_WORD_BYTES")?, "byte", "bytes"),
            "A longer run of letters is not looked up.".to_owned(),
        ],
        vec![
            "Fewest letters before a `*`".to_owned(),
            word("MIN_PREFIX_CHARS")?.to_string(),
            "`cra*` finds words that start with cra; `c*` is looked up as the word c.".to_owned(),
        ],
    ];
    let mut out = header("Limits of a search");
    out.push_str("A search that goes over a limit is told so in plain words below the box, before anything is sent to the server. The limits keep one search from keeping the server busy for everybody.\n\n");
    out.push_str(&table(&["What", "The most", "Note"], &rows));
    out.push_str("\nSee [Searching for issues](search.md).\n");
    Ok(out)
}

/// The times and counts of notifications, e-mail, signing up and handles.
fn notification_numbers(sources: &[Source]) -> anyhow::Result<String> {
    let of = |path: &str, name: &str| number(sources, path, name);
    let batch = of(NOTIFICATION_SOURCE, "MAIL_BATCH_SECONDS")?;
    let longest = of(NOTIFICATION_SOURCE, "MAIL_BATCH_SECONDS_MAX")?;
    if batch % 60 != 0 || longest % 3600 != 0 {
        bail!("the wait for e-mail is not whole minutes, or its longest is not whole hours");
    }
    let rows = vec![
        vec![
            "A notification is kept".to_owned(),
            counted(of(NOTIFICATION_SOURCE, "KEEP_DAYS")?, "day", "days"),
        ],
        vec![
            "The number on the menu counts up to".to_owned(),
            of(NOTIFICATION_SOURCE, "AT_ONCE_MAX")?.to_string(),
        ],
        vec![
            "Changes to one issue wait for each other before one e-mail goes".to_owned(),
            counted(batch / 60, "minute", "minutes"),
        ],
        vec![
            "The longest wait an organization may choose".to_owned(),
            counted(longest / 3600, "hour", "hours"),
        ],
        vec![
            "Between two test e-mails".to_owned(),
            counted(
                of(MAIL_SOURCE, "TEST_EMAIL_EVERY_SECONDS")?,
                "second",
                "seconds",
            ),
        ],
        vec![
            "The e-mail that signing up sends works".to_owned(),
            counted(of(SIGN_UP_SOURCE, "HOURS")?, "hour", "hours"),
        ],
        vec![
            "Another e-mail for the same address waits".to_owned(),
            counted(
                of(SIGN_UP_SOURCE, "RESEND_AFTER_MINUTES")?,
                "minute",
                "minutes",
            ),
        ],
        vec![
            "Between two changes of a handle".to_owned(),
            counted(of(HANDLE_SOURCE, "CHANGE_EVERY_DAYS")?, "day", "days"),
        ],
    ];
    let mut out = header("Times and counts of notifications");
    out.push_str("How long notifications are kept, when e-mails go, and how often some things may be done.\n\n");
    out.push_str(&table(&["What", "Number"], &rows));
    let _ = writeln!(
        out,
        "\nSee [Notifications](notifications.md) and [The mail server](mail-server.md)."
    );
    Ok(out)
}

/// The pages, each with its path.
pub(crate) fn pages(sources: &[Source]) -> anyhow::Result<Vec<(&'static str, String)>> {
    Ok(vec![
        (SEARCH_LIMITS_PAGE, search_limits(sources)?),
        (NOTIFICATION_NUMBERS_PAGE, notification_numbers(sources)?),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Sources that have every number the pages need, each as a constant of its file.
    fn sources() -> Vec<Source> {
        let file = |path: &str, names: &[(&str, u64)]| {
            let mut text = String::new();
            for (name, value) in names {
                let _ = writeln!(text, "pub const {name}: u64 = {value};");
            }
            (path.to_owned(), text)
        };
        vec![
            file(
                LIMITS_SOURCE,
                &[
                    ("MAX_FILTERS", 50),
                    ("MAX_CONTAINS_WORDS", 10),
                    ("MAX_SORT_KEYS", 5),
                    ("MAX_STEPS", 5),
                    ("MAX_DEPTH", 32),
                    ("MAX_TEXT_BYTES", 4096),
                ],
            ),
            file(
                WORDS_SOURCE,
                &[("MAX_WORD_BYTES", 255), ("MIN_PREFIX_CHARS", 2)],
            ),
            file(
                NOTIFICATION_SOURCE,
                &[
                    ("KEEP_DAYS", 90),
                    ("AT_ONCE_MAX", 100),
                    ("MAIL_BATCH_SECONDS", 300),
                    ("MAIL_BATCH_SECONDS_MAX", 24 * 60 * 60),
                ],
            ),
            file(MAIL_SOURCE, &[("TEST_EMAIL_EVERY_SECONDS", 1)]),
            file(
                SIGN_UP_SOURCE,
                &[("HOURS", 24), ("RESEND_AFTER_MINUTES", 10)],
            ),
            file(HANDLE_SOURCE, &[("CHANGE_EVERY_DAYS", 7)]),
        ]
    }

    #[test]
    fn the_pages_say_the_numbers_of_the_code_in_plain_words() {
        let pages = pages(&sources()).unwrap();
        let text = |path: &str| {
            pages
                .iter()
                .find(|(each, _)| *each == path)
                .map(|(_, text)| text.clone())
                .unwrap()
        };
        let limits = text(SEARCH_LIMITS_PAGE);
        assert!(limits.contains("| Filters in one search"), "{limits}");
        assert!(limits.contains("4096 bytes"), "{limits}");
        let numbers = text(NOTIFICATION_NUMBERS_PAGE);
        assert!(numbers.contains("90 days"), "{numbers}");
        assert!(numbers.contains("5 minutes"), "{numbers}");
        assert!(numbers.contains("24 hours"), "{numbers}");
        // One is said in the singular.
        assert!(numbers.contains("1 second "), "{numbers}");
    }

    #[test]
    fn a_wait_that_is_not_whole_minutes_is_refused() {
        let mut changed = sources();
        for (path, text) in &mut changed {
            if path == NOTIFICATION_SOURCE {
                *text = text.replace(
                    "MAIL_BATCH_SECONDS: u64 = 300",
                    "MAIL_BATCH_SECONDS: u64 = 301",
                );
            }
        }
        assert!(pages(&changed).is_err());
    }
}
