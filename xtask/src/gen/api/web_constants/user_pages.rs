/// The user page about the numbers of time and working hours.
pub(crate) const TIME_NUMBERS_PAGE: &str = "userDocs/working-hours/numbers.md";

const TIME_LIMITS_SOURCE: &str = "crates/bb-app/src/time/limits.rs";

const LIMITS_SOURCE: &str = "crates/bb-searchlang/src/limits.rs";
const WORDS_SOURCE: &str = "crates/bb-core/src/text_words.rs";

/// What a generated page says first.
fn header(title: &str) -> String {
    format!(
        "# {title}\n\nGENERATED by `cargo xtask gen api` from the numbers in the code. Do not edit this page by hand.\n\n"
    )
}

/// A number of the code, as a whole number.
fn number(sources: &[Source], path: &str, name: &str) -> anyhow::Result<u128> {
    let text = number_const(&parsed_file(sources, path)?, path, name)?;
    text.parse()
        .with_context(|| format!("{path}: `{name}` is {text}, not a whole number"))
}

/// `count` of a thing, in the singular for one.
fn counted(count: u128, one: &str, many: &str) -> String {
    format!("{count} {}", if count == 1 { one } else { many })
}

/// The limits of a search, in plain words.
fn search_limits(sources: &[Source]) -> anyhow::Result<String> {
    let limit = |name: &str| number(sources, LIMITS_SOURCE, name);
    let word = |name: &str| number(sources, WORDS_SOURCE, name);
    let rows = vec![
        vec![
            "Filters in one search".to_owned(),
            limit("MAX_FILTERS")?.to_string(),
            "`in (a, b, c)` counts as many filters as it has values.".to_owned(),
        ],
        vec![
            "Words in one `contains`".to_owned(),
            limit("MAX_CONTAINS_WORDS")?.to_string(),
            "A word that comes twice counts once.".to_owned(),
        ],
        vec![
            "Keys of `sort by`".to_owned(),
            limit("MAX_SORT_KEYS")?.to_string(),
            String::new(),
        ],
        vec![
            "Steps of `connected to … within N steps`".to_owned(),
            limit("MAX_STEPS")?.to_string(),
            String::new(),
        ],
        vec![
            "Brackets inside brackets".to_owned(),
            limit("MAX_DEPTH")?.to_string(),
            "`not` counts like a bracket.".to_owned(),
        ],
        vec![
            "Length of the text of a search".to_owned(),
            counted(limit("MAX_TEXT_BYTES")?, "byte", "bytes"),
            "Letters with accents and other scripts take more than one byte.".to_owned(),
        ],
        vec![
            "Longest word that is looked for".to_owned(),
            counted(word("MAX_WORD_BYTES")?, "byte", "bytes"),
            "A longer run of letters is not looked up.".to_owned(),
        ],
        vec![
            "Fewest letters before a `*`".to_owned(),
            word("MIN_PREFIX_CHARS")?.to_string(),
            "`cra*` finds words that start with cra; `c*` is looked up as the word c.".to_owned(),
        ],
    ];
    let mut out = header("Limits of a search");
    out.push_str("A search that goes over a limit is told so in plain words below the box, before anything is sent to the server. The limits keep one search from keeping the server busy for everybody.\n\n");
    out.push_str(&table(&["What", "The most", "Note"], &rows));
    out.push_str("\nSee [Searching for issues](search.md).\n");
    Ok(out)
}

/// The times and counts of notifications, e-mail, signing up and handles.
fn notification_numbers(sources: &[Source]) -> anyhow::Result<String> {
    let of = |path: &str, name: &str| number(sources, path, name);
    let batch = of(NOTIFICATION_SOURCE, "MAIL_BATCH_SECONDS")?;
    let longest = of(NOTIFICATION_SOURCE, "MAIL_BATCH_SECONDS_MAX")?;
    if batch % 60 != 0 || longest % 3600 != 0 {
        bail!("the wait for e-mail is not whole minutes, or its longest is not whole hours");
    }
    let rows = vec![
        vec![
            "A notification is kept".to_owned(),
            counted(of(NOTIFICATION_SOURCE, "KEEP_DAYS")?, "day", "days"),
        ],
        vec![
            "The number on the menu counts up to".to_owned(),
            of(NOTIFICATION_SOURCE, "AT_ONCE_MAX")?.to_string(),
        ],
        vec![
            "Changes to one issue wait for each other before one e-mail goes".to_owned(),
            counted(batch / 60, "minute", "minutes"),
        ],
        vec![
            "The longest wait an organization may choose".to_owned(),
            counted(longest / 3600, "hour", "hours"),
        ],
        vec![
            "Between two test e-mails".to_owned(),
            counted(
                of(MAIL_SOURCE, "TEST_EMAIL_EVERY_SECONDS")?,
                "second",
                "seconds",
            ),
        ],
        vec![
            "The e-mail that signing up sends works".to_owned(),
            counted(of(SIGN_UP_SOURCE, "HOURS")?, "hour", "hours"),
        ],
        vec![
            "Another e-mail for the same address waits".to_owned(),
            counted(
                of(SIGN_UP_SOURCE, "RESEND_AFTER_MINUTES")?,
                "minute",
                "minutes",
            ),
        ],
        vec![
            "Between two changes of a handle".to_owned(),
            counted(of(HANDLE_SOURCE, "CHANGE_EVERY_DAYS")?, "day", "days"),
        ],
    ];
    let mut out = header("Times and counts of notifications");
    out.push_str("How long notifications are kept, when e-mails go, and how often some things may be done.\n\n");
    out.push_str(&table(&["What", "Number"], &rows));
    let _ = writeln!(
        out,
        "\nSee [Notifications](notifications.md) and [The mail server](mail-server.md)."
    );
    Ok(out)
}

/// A length in minutes in plain words: whole hours as hours, else minutes.
fn minutes_said(minutes: u128) -> String {
    const PER_HOUR: u128 = 60;
    if minutes != 0 && minutes.is_multiple_of(PER_HOUR) {
        counted(minutes / PER_HOUR, "hour", "hours")
    } else {
        counted(minutes, "minute", "minutes")
    }
}

/// The default of a whole-number setting of the registry.
fn default_of(key: &str) -> anyhow::Result<u128> {
    match bb_core::settings::find(key).map(bb_core::settings::SettingDefinition::default) {
        Some(bb_core::settings::DefaultValue::Integer(value)) => u128::try_from(value)
            .with_context(|| format!("the default of `{key}` is {value}, which is below zero")),
        _ => bail!("`{key}` is not a whole-number setting of the registry"),
    }
}

/// The rows of the working-time rules of the preset *Germany*, from the defaults of the registry.
fn rule_rows() -> anyhow::Result<Vec<Vec<String>>> {
    let rule = |key: &str, what: &str, note: &str| -> anyhow::Result<Vec<String>> {
        Ok(vec![
            what.to_owned(),
            minutes_said(default_of(key)?),
            note.to_owned(),
        ])
    };
    Ok(vec![
        rule(
            "working-hours.day-minutes-max",
            "The longest work day",
            "More is a warning.",
        )?,
        rule(
            "working-hours.first-break-after-minutes",
            "The first break is due after",
            "Work of more than this needs a break.",
        )?,
        rule(
            "working-hours.first-break-minutes",
            "Length of the first break",
            "The breaks of the day together.",
        )?,
        rule(
            "working-hours.second-break-after-minutes",
            "The longer break is due after",
            "",
        )?,
        rule(
            "working-hours.second-break-minutes",
            "Length of the longer break",
            "The breaks of the day together.",
        )?,
        rule(
            "working-hours.shortest-break-minutes",
            "The shortest break that counts",
            "A shorter one is no break.",
        )?,
        rule(
            "working-hours.in-a-row-minutes-max",
            "The longest stretch without a break",
            "",
        )?,
        rule(
            "working-hours.rest-minutes-min",
            "The rest between two work days",
            "",
        )?,
    ])
}

/// The working-time rules of the preset *Germany*, the keep period and the limits of time on issues
/// (the registry and the constants of the code).
fn time_numbers(sources: &[Source]) -> anyhow::Result<String> {
    let rules = rule_rows()?;
    let limit = |name: &str| number(sources, TIME_LIMITS_SOURCE, name);
    let entry_most = u128::from(bb_core::time::length::TIME_ENTRY_MINUTES_MAX.get());
    let entry_least = u128::from(bb_core::time::length::TIME_ENTRY_MINUTES_MIN.get());
    let keep = default_of("working-hours.keep-years")?;
    let least = u128::try_from(bb_core::working_time::GERMANY_KEEP_YEARS_LEAST)
        .context("the least keep period is below zero")?;
    let time = vec![
        vec![
            "A time entry is at least".to_owned(),
            minutes_said(entry_least),
        ],
        vec![
            "A time entry is at most".to_owned(),
            minutes_said(entry_most),
        ],
        vec![
            "Time entries on one date".to_owned(),
            format!("{} at most", limit("TIME_ENTRIES_PER_DAY_MAX")?),
        ],
        vec![
            "The note of a time entry".to_owned(),
            format!(
                "{} at most",
                counted(limit("TIME_NOTE_CHARS_MAX")?, "character", "characters")
            ),
        ],
        vec![
            "A timer shows a warning after".to_owned(),
            counted(limit("LONG_TIMER_HOURS")?, "hour", "hours"),
        ],
        vec![
            "Work days are kept at least".to_owned(),
            format!(
                "{} (with the preset Germany, never less than {})",
                counted(keep, "year", "years"),
                counted(least, "year", "years")
            ),
        ],
    ];
    let mut out = header("Numbers of working hours and time");
    out.push_str("The rules of the preset *Germany* are the numbers an organization starts with; an administrator can change each one (see [The settings of working hours and time](README.md)). A rule that is broken only gives a warning.

");
    out.push_str(&table(&["Rule", "Number", "Note"], &rules));
    out.push_str(
        "
The limits of time on issues and of the keep period:

",
    );
    out.push_str(&table(&["What", "Number"], &time));
    out.push_str(
        "
See [Time](../time/README.md) and [The timesheet](../time/timesheet.md).
",
    );
    Ok(out)
}

/// The numbers of the assistant, of AI apps and of agents, in plain words. They come from the
/// constants of `bb-core` that the code works by, so the guide never writes one a second time.
fn ai_numbers() -> anyhow::Result<String> {
    use bb_core::agent::{
        DEFAULT_ATTEMPTS_ON_ONE_ISSUE, DEFAULT_CHANGES_A_MINUTE, DEFAULT_ISSUES_AT_ONCE,
        MOST_AGENT_KEYS, MOST_AGENTS, MOST_ISSUES_OF_ONE_CHANGE,
    };
    use bb_core::agent_work::{
        DEFAULT_HAND_OVER_DAYS, DEFAULT_RULE_DAYS, MOST_HAND_OVER_DAYS, MOST_ISSUES_OF_A_HAND_OVER,
        MOST_RULE_DAYS, RULE_WARNING_DAYS,
    };
    use bb_core::ai::{
        PROPOSAL_LIFETIME_SECONDS, PROPOSALS_MAX, QUESTION_CHARS_MAX, TOOL_CALL_KEEP_DAYS,
        TOOL_CALLS_MAX, TURN_CHARS_MAX, TURNS_MAX,
    };
    let minutes = u128::try_from(PROPOSAL_LIFETIME_SECONDS / 60)
        .context("the life of a proposal is below zero")?;
    let rows = |rows: Vec<(&str, String)>| -> Vec<Vec<String>> {
        rows.into_iter()
            .map(|(what, number)| vec![what.to_owned(), number])
            .collect()
    };
    let assistant = rows(vec![
        (
            "A question to the assistant is at most",
            counted(QUESTION_CHARS_MAX as u128, "character", "characters"),
        ),
        (
            "A conversation keeps at most",
            counted(TURNS_MAX as u128, "turn", "turns"),
        ),
        (
            "A turn is at most",
            counted(TURN_CHARS_MAX as u128, "character", "characters"),
        ),
        (
            "The assistant looks things up at most",
            format!(
                "{} for one question",
                counted(TOOL_CALLS_MAX as u128, "time", "times")
            ),
        ),
        (
            "The assistant proposes at most",
            format!(
                "{} at once; a proposal waits {} for *Apply*",
                counted(PROPOSALS_MAX as u128, "change", "changes"),
                counted(minutes, "minute", "minutes")
            ),
        ),
        (
            "The calls of tools are kept for",
            counted(
                u128::try_from(TOOL_CALL_KEEP_DAYS).context("the keep period is below zero")?,
                "day",
                "days",
            ),
        ),
    ]);
    let day = |days: i64| -> anyhow::Result<String> {
        Ok(counted(
            u128::try_from(days).context("a number of days is below zero")?,
            "day",
            "days",
        ))
    };
    let agents = rows(vec![
        (
            "A person has at most",
            counted(MOST_AGENTS as u128, "agent", "agents"),
        ),
        (
            "An agent has at most",
            counted(MOST_AGENT_KEYS as u128, "key", "keys"),
        ),
        (
            "A new agent is held to at most",
            format!(
                "{} a minute",
                counted(
                    u128::try_from(DEFAULT_CHANGES_A_MINUTE).context("below zero")?,
                    "change",
                    "changes"
                )
            ),
        ),
        (
            "A new agent works on at most",
            format!(
                "{} at once",
                counted(
                    u128::try_from(DEFAULT_ISSUES_AT_ONCE).context("below zero")?,
                    "issue",
                    "issues"
                )
            ),
        ),
        (
            "A new agent may try one issue at most",
            counted(
                u128::try_from(DEFAULT_ATTEMPTS_ON_ONE_ISSUE).context("below zero")?,
                "time",
                "times",
            ),
        ),
        (
            "One hand-over names at most",
            counted(MOST_ISSUES_OF_A_HAND_OVER as u128, "issue", "issues"),
        ),
        (
            "A hand-over ends after",
            format!(
                "{} unless you choose another end, at most {}",
                day(DEFAULT_HAND_OVER_DAYS)?,
                day(MOST_HAND_OVER_DAYS)?
            ),
        ),
        (
            "A standing rule ends after",
            format!(
                "{} unless you choose another end, at most {}; you are told {} before",
                day(DEFAULT_RULE_DAYS)?,
                day(MOST_RULE_DAYS)?,
                day(RULE_WARNING_DAYS)?
            ),
        ),
        (
            "A change to many issues, also by an agent, names at most",
            counted(MOST_ISSUES_OF_ONE_CHANGE as u128, "issue", "issues"),
        ),
    ]);
    let mut out = header("Numbers of the assistant, AI apps and agents");
    out.push_str("The limits of the assistant and of agents, as Bugaboo works by them. An administrator can set a lower maximum for what an agent may do (*Organization settings › Connections › Agents*).\n\n## The assistant\n\n");
    out.push_str(&table(&["What", "Number"], &assistant));
    out.push_str("\n## Agents\n\n");
    out.push_str(&table(&["What", "Number"], &agents));
    out.push_str("\nSee [The AI literacy guide](literacy.md) and [Agents](../agents/README.md).\n");
    Ok(out)
}

/// The pages, each with its path.
pub(crate) fn pages(sources: &[Source]) -> anyhow::Result<Vec<(&'static str, String)>> {
    Ok(vec![
        (SEARCH_LIMITS_PAGE, search_limits(sources)?),
        (NOTIFICATION_NUMBERS_PAGE, notification_numbers(sources)?),
        (TIME_NUMBERS_PAGE, time_numbers(sources)?),
        (AI_NUMBERS_PAGE, ai_numbers()?),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Sources that have every number the pages need, each as a constant of its file.
    fn sources() -> Vec<Source> {
        let file = |path: &str, names: &[(&str, u64)]| {
            let mut text = String::new();
            for (name, value) in names {
                let _ = writeln!(text, "pub const {name}: u64 = {value};");
            }
            (path.to_owned(), text)
        };
        vec![
            file(
                LIMITS_SOURCE,
                &[
                    ("MAX_FILTERS", 50),
                    ("MAX_CONTAINS_WORDS", 10),
                    ("MAX_SORT_KEYS", 5),
                    ("MAX_STEPS", 5),
                    ("MAX_DEPTH", 32),
                    ("MAX_TEXT_BYTES", 4096),
                ],
            ),
            file(
                WORDS_SOURCE,
                &[("MAX_WORD_BYTES", 255), ("MIN_PREFIX_CHARS", 2)],
            ),
            file(
                NOTIFICATION_SOURCE,
                &[
                    ("KEEP_DAYS", 90),
                    ("AT_ONCE_MAX", 100),
                    ("MAIL_BATCH_SECONDS", 300),
                    ("MAIL_BATCH_SECONDS_MAX", 24 * 60 * 60),
                ],
            ),
            file(MAIL_SOURCE, &[("TEST_EMAIL_EVERY_SECONDS", 1)]),
            file(
                SIGN_UP_SOURCE,
                &[("HOURS", 24), ("RESEND_AFTER_MINUTES", 10)],
            ),
            file(HANDLE_SOURCE, &[("CHANGE_EVERY_DAYS", 7)]),
            file(
                TIME_LIMITS_SOURCE,
                &[
                    ("TIME_ENTRIES_PER_DAY_MAX", 200),
                    ("TIME_NOTE_CHARS_MAX", 2000),
                    ("LONG_TIMER_HOURS", 10),
                ],
            ),
        ]
    }

    #[test]
    fn the_pages_say_the_numbers_of_the_code_in_plain_words() {
        let pages = pages(&sources()).unwrap();
        let text = |path: &str| {
            pages
                .iter()
                .find(|(each, _)| *each == path)
                .map(|(_, text)| text.clone())
                .unwrap()
        };
        let limits = text(SEARCH_LIMITS_PAGE);
        assert!(limits.contains("| Filters in one search"), "{limits}");
        assert!(limits.contains("4096 bytes"), "{limits}");
        let numbers = text(NOTIFICATION_NUMBERS_PAGE);
        assert!(numbers.contains("90 days"), "{numbers}");
        assert!(numbers.contains("5 minutes"), "{numbers}");
        assert!(numbers.contains("24 hours"), "{numbers}");
        // One is said in the singular.
        assert!(numbers.contains("1 second "), "{numbers}");
    }

    #[test]
    fn the_page_of_time_says_the_rules_of_germany_and_the_limits_of_the_code() {
        let pages = pages(&sources()).unwrap();
        let page = pages
            .iter()
            .find(|(each, _)| *each == TIME_NUMBERS_PAGE)
            .map(|(_, text)| text.clone())
            .unwrap();
        assert!(page.contains("| The longest work day"), "{page}");
        assert!(page.contains("10 hours"), "{page}");
        assert!(page.contains("45 minutes"), "{page}");
        assert!(page.contains("200 at most"), "{page}");
        assert!(page.contains("24 hours"), "{page}");
        assert!(page.contains("never less than 2 years"), "{page}");
    }

    #[test]
    fn the_page_of_ai_says_the_limits_of_the_code() {
        let pages = pages(&sources()).unwrap();
        let page = pages
            .iter()
            .find(|(each, _)| *each == AI_NUMBERS_PAGE)
            .map(|(_, text)| text.clone())
            .unwrap();
        assert!(
            page.contains("| A question to the assistant is at most"),
            "{page}"
        );
        assert!(page.contains("100 issues"), "{page}");
        assert!(page.contains("at most 90 days"), "{page}");
        assert!(page.contains("you are told 3 days before"), "{page}");
    }

    #[test]
    fn a_wait_that_is_not_whole_minutes_is_refused() {
        let mut changed = sources();
        for (path, text) in &mut changed {
            if path == NOTIFICATION_SOURCE {
                *text = text.replace(
                    "MAIL_BATCH_SECONDS: u64 = 300",
                    "MAIL_BATCH_SECONDS: u64 = 301",
                );
            }
        }
        assert!(pages(&changed).is_err());
    }
}
