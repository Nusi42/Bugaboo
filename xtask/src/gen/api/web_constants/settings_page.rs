//! The user page of the start-up settings and their environment variables
//! (`userDocs/install/settings.md`), read from the one list of the settings in the server
//! (`SettingName` in `crates/bb-server/src/config.rs`) and the rule that names a variable, so the
//! page never lists a setting a second time by hand.

use std::fmt::Write as _;

use anyhow::Context as _;

use super::text_const;
use crate::source::Source;

/// The user page of the start-up settings.
pub(crate) const SETTINGS_PAGE: &str = "userDocs/install/settings.md";

/// Where the start-up settings are declared.
pub(super) const CONFIG_SOURCE: &str = "crates/bb-server/src/config.rs";
/// The enum of the start-up settings in its `words!` table.
const SETTING_ENUM: &str = "enum SettingName";

/// The words of the start-up settings, in the order of the table.
fn setting_words(text: &str) -> anyhow::Result<Vec<String>> {
    let file = syn::parse_file(text).with_context(|| format!("{CONFIG_SOURCE} is not Rust"))?;
    let table = file
        .items
        .iter()
        .find_map(|item| match item {
            syn::Item::Macro(item) if item.mac.path.is_ident("words") => {
                let tokens = item.mac.tokens.to_string();
                tokens.contains(SETTING_ENUM).then_some(tokens)
            }
            _ => None,
        })
        .with_context(|| format!("{CONFIG_SOURCE} has no `words!` table with `{SETTING_ENUM}`"))?;
    let words: Vec<String> = table
        .split("=>")
        .skip(1)
        .filter_map(|after| after.split('"').nth(1).map(str::to_owned))
        .collect();
    anyhow::ensure!(
        !words.is_empty(),
        "{CONFIG_SOURCE}: `{SETTING_ENUM}` has no words"
    );
    Ok(words)
}

/// The page: every setting with its environment variable, and where the settings file is.
pub(crate) fn settings_page(sources: &[Source]) -> anyhow::Result<String> {
    let Some((_, text)) = sources.iter().find(|(path, _)| path == CONFIG_SOURCE) else {
        anyhow::bail!("{CONFIG_SOURCE} is missing");
    };
    let text_of = |name: &str| {
        text_const(text, name).with_context(|| format!("{CONFIG_SOURCE} has no text `{name}`"))
    };
    let (prefix, file_env, default_file) = (
        text_of("ENV_PREFIX")?,
        text_of("FILE_ENV")?,
        text_of("DEFAULT_FILE")?,
    );
    let mut out = format!(
        "# Start-up settings

<!-- GENERATED by `cargo xtask gen api` from the settings in the code. Do not edit this page by hand. -->

Bugaboo reads these settings when it starts, the strongest first: the command line, an environment variable, the settings file `{default_file}`, and the built-in default. Each setting has the same name everywhere. Its environment variable is `{prefix}` followed by the name in capitals. Another settings file is named with `--config` or the variable `{file_env}`.

| Setting in `{default_file}` | Environment variable |
| --- | --- |
"
    );
    for word in setting_words(text)? {
        let _ = writeln!(
            out,
            "| `{word}` | `{prefix}{}` |",
            word.to_ascii_uppercase()
        );
    }
    out.push_str(
        "\nA PostgreSQL server on another computer is reached safely only when Bugaboo checks its \
         certificate: add `sslmode=verify-full` to `database_url`, as in \
         `postgres://bugaboo@db.example.com/bugaboo?sslmode=verify-full`. `bugaboo setup` adds it \
         for a server on another computer when the address says nothing about `sslmode`. Without \
         it, somebody in between could read or change what passes, the password \
         included, and Bugaboo warns at every start and on the status page. A server on this \
         computer (`localhost`, `127.0.0.1` or a Unix socket) needs nothing.\n",
    );
    out.push_str(
        "\n`database_url` must lead to the PostgreSQL server itself, or to a pooler of connections \
         that gives each client a connection of its own for as long as it is connected. A pooler \
         that hands connections to other clients between changes (as PgBouncer does in its most \
         common setting) would let go of the hold that every running server keeps on its \
         database, and `bugaboo restore` could not see that a server still uses it.\n",
    );
    out.push_str("\nWhat each setting means is in [Install Bugaboo](README.md).\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_lists_every_setting_with_its_variable() {
        let config = r#"
words! {
    /// Every start-up setting, once. The word is "the name".
    pub(crate) enum SettingName {
        /// Where it listens.
        Address => "address",
        PublicUrl => "public_url",
    }
}
const ENV_PREFIX: &str = "BUGABOO_";
pub(crate) const FILE_ENV: &str = "BUGABOO_CONFIG";
pub(crate) const DEFAULT_FILE: &str = "bugaboo.toml";
"#;
        let page = settings_page(&[(CONFIG_SOURCE.to_owned(), config.to_owned())]).unwrap();
        assert!(page.contains("| `address` | `BUGABOO_ADDRESS` |"), "{page}");
        assert!(
            page.contains("| `public_url` | `BUGABOO_PUBLIC_URL` |"),
            "{page}"
        );
        assert!(page.contains("`BUGABOO_CONFIG`"), "{page}");
        assert!(!page.contains("THE NAME"), "{page}");
    }
}
