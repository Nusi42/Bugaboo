//! `cargo xtask gen search-types`: the TypeScript types of what `bb-wasm-search` takes and gives,
//! from the Rust types of `bb-searchlang` (coding-standards section 1).
//!
//! The browser sends a tree and a field catalogue to the module as JSON and reads the answer, the
//! mistakes and the suggestions back. The Rust types are the one declaration;
//! `web/packages/wasm-search/src/types.generated.ts` is written from them with the same reader as
//! the book of a load run (`load_book.rs`), and DOC-GENERATED fails when the file is not what the
//! types give.

use anyhow::Context as _;

use super::Generated;
use super::api::format_with_oxfmt;
use super::load_book::types_under;
use crate::repo::Repo;
use crate::source::read_text;

/// The generated file, relative to the repository root.
pub(crate) const OUTPUT: &str = "web/packages/wasm-search/src/types.generated.ts";
/// The Rust files it is made from, in the order of the types in the output.
const SOURCES: [&str; 7] = [
    "crates/bb-searchlang/src/span.rs",
    "crates/bb-searchlang/src/syntax.rs",
    "crates/bb-searchlang/src/catalogue.rs",
    "crates/bb-searchlang/src/mistake.rs",
    "crates/bb-searchlang/src/suggest.rs",
    "crates/bb-searchlang/src/answer.rs",
    "crates/bb-searchlang/src/vectors.rs",
];
const HEADER: &str = "// Generated by `cargo xtask gen search-types`. Do not edit by hand.\n\n";

/// The text of the generated file, before it is formatted. The files are read as one: the comments
/// and attributes that belong to a whole file (`//!`, `#![…]`) are left out, because only the first
/// file could carry them.
fn types_of(sources: &[String]) -> anyhow::Result<String> {
    let one: Vec<&str> = sources
        .iter()
        .flat_map(|source| source.lines())
        .filter(|line| !line.starts_with("//!") && !line.starts_with("#!["))
        .collect();
    types_under(
        &one.join(
            "
",
        ),
        HEADER,
    )
}

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    let mut sources = Vec::new();
    for path in SOURCES {
        sources.push(read_text(repo, path)?);
    }
    let text =
        types_of(&sources).context("the types of bb-searchlang cannot be written as types")?;
    Ok(vec![Generated::new(
        OUTPUT,
        format_with_oxfmt(repo, OUTPUT, &text)?,
    )])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_types_of_the_search_language_can_be_written_as_types() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap_or(std::path::Path::new("."));
        let sources: Vec<String> = SOURCES
            .iter()
            .map(|path| std::fs::read_to_string(root.join(path)).unwrap_or_default())
            .collect();
        let text = types_of(&sources).unwrap_or_default();
        for expected in [
            "export type Expr =",
            "readonly item: Expr;",
            "export interface Search {",
            "readonly filter: Expr | null;",
            "export interface Mistake {",
            "readonly args: Readonly<Record<string, string>>;",
            "export type Suggestion =",
            "export interface Answer {",
            "export interface FieldCatalogue {",
        ] {
            assert!(text.contains(expected), "{expected}: {text}");
        }
    }
}
