//! `cargo xtask gen theme`: everything that is made from `design/theme.kdl` (ADR-0026).
//!
//! - the one static style sheet: the variables of every theme and mode, then the rules of the
//!   parts. It is compiled at build time, so the page keeps `style-src 'self'`;
//! - the TypeScript names of the themes, tokens and parts;
//! - the theme choices of the settings registry in Rust;
//! - the copy of the style sheet that the design pages use.

use std::fmt::Write as _;

use anyhow::{Context as _, bail};

use super::Generated;
use super::theme_file::{
    Declaration, Item, Keyframes, Rule, RuleKind, ThemeFile, Token, TokenKind, Variant, references,
    substitute,
};
use super::theme_selector;
use crate::repo::Repo;

/// The one style sheet of the browser app (the only CSS file of `web/`, THEME-ONLY).
pub(crate) const STYLE_SHEET: &str = "web/packages/ui/src/theme.css";
/// The design pages' copy: the themes and the tokens, without the rules of the components (the
/// pages have their own, `components.css`).
const DOCS_SHEET: &str = "docs/design/theme.css";
const TS_OUTPUT: &str = "web/packages/ui/src/tokens.ts";
const RUST_OUTPUT: &str = "crates/bb-core/src/settings/themes.rs";

const GENERATED_BY: &str =
    "Generated by `cargo xtask gen theme` from design/theme.kdl. Do not edit by hand.";

/// The paths [`outputs`] writes.
pub(crate) fn output_paths() -> Vec<&'static str> {
    let mut paths = vec![STYLE_SHEET, DOCS_SHEET];
    paths.push(TS_OUTPUT);
    paths.push(RUST_OUTPUT);
    paths
}

/// The generated files, from `design/theme.kdl` on disk.
pub(crate) fn outputs(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    generate(&ThemeFile::load(repo)?)
}

pub(crate) fn generate(file: &ThemeFile) -> anyhow::Result<Vec<Generated>> {
    Ok(vec![
        Generated::new(STYLE_SHEET, css(file)?),
        Generated::new(DOCS_SHEET, tokens_only_css(file)),
        Generated::new(TS_OUTPUT, typescript(file)?),
        Generated::new(RUST_OUTPUT, rust(file)),
    ])
}

/// The whole style sheet.
pub(crate) fn css(file: &ThemeFile) -> anyhow::Result<String> {
    let mut out = tokens_only_css(file);
    let parts = parts_css(file)?;
    if !parts.is_empty() {
        out.push('\n');
        out.push_str(&parts);
    }
    Ok(out)
}

// ───────────── Tokens ─────────────

/// The variables of every theme and mode, without the rules of the components.
fn tokens_only_css(file: &ThemeFile) -> String {
    let mut out = css_header(file);
    out.push_str(&token_css(file));
    out
}

fn token_css(file: &ThemeFile) -> String {
    let light = file.default_light.as_str();
    let dark = file.default_dark.as_str();
    let mut out = String::from(":root {\n");
    for token in &file.tokens {
        if let Some(value) = &token.same {
            let _ = writeln!(out, "  --{}: {};", token.name, substitute(value));
        }
    }
    theme_declarations(&mut out, file, light, "  ", false);
    out.push_str("}\n\n");
    out.push_str("@media (prefers-color-scheme: dark) {\n");
    out.push_str("  :root:not([data-theme=\"light\"]) {\n");
    theme_declarations(&mut out, file, dark, "    ", false);
    out.push_str("  }\n}\n\n");
    out.push_str(":root[data-theme=\"dark\"] {\n");
    theme_declarations(&mut out, file, dark, "  ", false);
    out.push_str("}\n");
    for theme in &file.themes {
        // The same colors for a sample of a theme next to the page's own (`data-preview-look`):
        // *My settings* shows each theme as it looks before it is chosen.
        let _ = write!(
            out,
            "\n:root[data-look=\"{0}\"],\n[data-preview-look=\"{0}\"] {{\n",
            theme.name
        );
        theme_declarations(&mut out, file, &theme.name, "  ", false);
        out.push_str("}\n");
    }
    for variant in &file.variants {
        variant_blocks(&mut out, file, variant);
    }
    more_contrast_blocks(&mut out, file);
    forced_block(&mut out, file);
    out
}

/// The tokens that differ by theme, as one theme has them; with `only_more`, only the ones that
/// change when the device asks for more contrast.
fn theme_declarations(
    out: &mut String,
    file: &ThemeFile,
    theme: &str,
    indent: &str,
    only_more: bool,
) {
    for token in &file.tokens {
        let value = if only_more {
            token
                .more
                .iter()
                .find(|(name, _)| name == theme)
                .map(|(_, value)| value.as_str())
        } else {
            token.in_theme(theme)
        };
        if let Some(value) = value {
            let _ = writeln!(out, "{indent}--{}: {};", token.name, substitute(value));
        }
    }
    if !only_more {
        let kind = file
            .theme(theme)
            .map_or("light", |theme| theme.kind.as_str());
        let _ = writeln!(out, "{indent}color-scheme: {kind};");
    }
}

/// What a choice (spacing, text size, motion) changes, switched on by its attribute on `<html>`
/// and, where it has one, by the device setting too.
fn variant_blocks(out: &mut String, file: &ThemeFile, variant: &Variant) {
    let changed: Vec<(&Token, &str)> = file
        .tokens
        .iter()
        .filter_map(|token| {
            token
                .variants
                .iter()
                .find(|(name, _)| *name == variant.name)
                .map(|(_, value)| (token, value.as_str()))
        })
        .collect();
    let declarations = |out: &mut String, indent: &str| {
        for (token, value) in &changed {
            let _ = writeln!(out, "{indent}--{}: {};", token.name, substitute(value));
        }
    };
    if let Some(media) = &variant.media {
        let _ = write!(out, "\n@media {media} {{\n  :root {{\n");
        declarations(out, "    ");
        out.push_str("  }\n}\n");
    }
    let _ = write!(
        out,
        "\n:root[{}=\"{}\"] {{\n",
        variant.attribute, variant.value
    );
    declarations(out, "  ");
    out.push_str("}\n");
}

/// The colors that change for people whose device asks for more contrast, for every way a theme
/// is put on the page (the device fallback, `data-theme`, `data-look`).
fn more_contrast_blocks(out: &mut String, file: &ThemeFile) {
    let (light, dark) = (file.default_light.as_str(), file.default_dark.as_str());
    out.push_str("\n@media (prefers-contrast: more) {\n  :root {\n");
    theme_declarations(out, file, light, "    ", true);
    out.push_str("  }\n}\n");
    out.push_str(
        "\n@media (prefers-contrast: more) and (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n",
    );
    theme_declarations(out, file, dark, "    ", true);
    out.push_str("  }\n}\n");
    out.push_str("\n@media (prefers-contrast: more) {\n  :root[data-theme=\"dark\"] {\n");
    theme_declarations(out, file, dark, "    ", true);
    out.push_str("  }\n");
    for theme in &file.themes {
        let _ = writeln!(
            out,
            "  :root[data-look=\"{0}\"],\n  [data-preview-look=\"{0}\"] {{",
            theme.name
        );
        theme_declarations(out, file, &theme.name, "    ", true);
        out.push_str("  }\n");
    }
    out.push_str("}\n");
}

/// The values for forced colors, where the device replaces the colors of the page by its own.
fn forced_block(out: &mut String, file: &ThemeFile) {
    let forced: Vec<&Token> = file
        .tokens
        .iter()
        .filter(|token| token.forced.is_some())
        .collect();
    if forced.is_empty() {
        return;
    }
    // The same selectors as every block that sets the colors of a theme, and after them, so that
    // the forced values win over each of them (`:root[data-look]` weighs more than `:root`).
    let mut selectors = vec![
        ":root".to_owned(),
        ":root:not([data-theme=\"light\"])".to_owned(),
        ":root[data-theme=\"dark\"]".to_owned(),
    ];
    for theme in &file.themes {
        selectors.push(format!(":root[data-look=\"{}\"]", theme.name));
        selectors.push(format!("[data-preview-look=\"{}\"]", theme.name));
    }
    let _ = write!(out, "\n@media {} {{\n", super::theme_file::FORCED_QUERY);
    let _ = writeln!(out, "  {} {{", selectors.join(",\n  "));
    for token in forced {
        if let Some(value) = &token.forced {
            let _ = writeln!(out, "    --{}: {};", token.name, substitute(value));
        }
    }
    out.push_str("  }\n}\n");
}

/// The generated-file notice followed by an explanation built from the theme data.
fn css_header(file: &ThemeFile) -> String {
    let names: Vec<String> = file
        .themes
        .iter()
        .map(|theme| title_case(&theme.name))
        .collect();
    let fonts: Vec<&str> = file
        .tokens
        .iter()
        .filter(|token| token.kind == TokenKind::Font)
        .filter_map(|token| token.same.as_deref())
        .filter_map(|stack| stack.split(',').next())
        .map(|name| name.trim().trim_matches('"'))
        .collect();
    format!(
        "/* {GENERATED_BY}
   {count} built-in themes: {names}. Pages set <html data-look=\"…\">;
   without it, \"Match my device\" falls back to {light} (light) / {dark} (dark).
   Load fonts separately: {fonts}. */
",
        count = names.len(),
        names = names.join(", "),
        light = title_case(&file.default_light),
        dark = title_case(&file.default_dark),
        fonts = fonts.join(" + "),
    )
}

fn title_case(name: &str) -> String {
    let mut letters = name.chars();
    letters
        .next()
        .map(|first| first.to_uppercase().chain(letters).collect())
        .unwrap_or_default()
}

// ───────────── Rules ─────────────

/// The keyframes and the rules of the file, as CSS: the same text the token variables come before.
pub(crate) fn parts_css(file: &ThemeFile) -> anyhow::Result<String> {
    let mut blocks = Vec::new();
    for keyframes in &file.keyframes {
        blocks.push(keyframes_css(keyframes));
    }
    for rule in &file.rules {
        blocks
            .push(rule_css(file, rule).with_context(|| format!("the rule at line {}", rule.line))?);
    }
    Ok(blocks.join("\n"))
}

fn keyframes_css(keyframes: &Keyframes) -> String {
    let mut out = format!("@keyframes {} {{\n", keyframes.name);
    for (frame, declarations) in &keyframes.frames {
        let _ = writeln!(out, "  {frame} {{");
        for declaration in declarations {
            let _ = writeln!(
                out,
                "    {}: {};",
                declaration.property,
                substitute(&declaration.value)
            );
        }
        out.push_str("  }\n");
    }
    out.push_str("}\n");
    out
}

fn rule_css(file: &ThemeFile, rule: &Rule) -> anyhow::Result<String> {
    let selectors = rule
        .selectors
        .iter()
        .map(|selector| match rule.kind {
            RuleKind::Part => theme_selector::compile(selector),
            RuleKind::Base => theme_selector::check_base(selector).map(|()| {
                // The formatter puts each selector of a list on a line of its own.
                selector.split(',').map(str::trim).collect::<Vec<_>>().join(
                    ",
",
                )
            }),
        })
        .collect::<anyhow::Result<Vec<_>>>()?;
    let selector = selectors.join(",\n");
    let mut plain = Vec::new();
    let mut media = Vec::new();
    flatten(file, &rule.items, &mut plain, &mut media, 0)?;
    let mut out = String::new();
    if !plain.is_empty() {
        out.push_str(&block(&selector, &plain, ""));
    }
    for (query, declarations) in media {
        let query = resolve_query(file, &query)?;
        let _ = writeln!(out, "\n@media {query} {{");
        out.push_str(&block(&selector, &declarations, "  "));
        out.push_str("}\n");
    }
    Ok(out.trim_start_matches('\n').to_owned())
}

fn block(selector: &str, declarations: &[&Declaration], indent: &str) -> String {
    let selector = selector
        .lines()
        .map(|line| format!("{indent}{line}"))
        .collect::<Vec<_>>()
        .join("\n");
    let mut out = format!("{selector} {{\n");
    for declaration in declarations {
        let _ = writeln!(
            out,
            "{indent}  {}: {};",
            declaration.property,
            substitute(&declaration.value)
        );
    }
    let _ = writeln!(out, "{indent}}}");
    out
}

/// How deep `use` may go before the mixins are taken to call each other in a circle.
const MIXIN_DEPTH: usize = 8;

type Blocks<'a> = Vec<(String, Vec<&'a Declaration>)>;

/// The lines of a rule with the mixins put in, and the lines under each media query apart.
fn flatten<'a>(
    file: &'a ThemeFile,
    items: &'a [Item],
    plain: &mut Vec<&'a Declaration>,
    media: &mut Blocks<'a>,
    depth: usize,
) -> anyhow::Result<()> {
    if depth > MIXIN_DEPTH {
        bail!("mixins call each other in a circle");
    }
    for item in items {
        match item {
            Item::Declaration(declaration) => plain.push(declaration),
            Item::Use { mixin, .. } => {
                let mixin = file
                    .mixins
                    .iter()
                    .find(|candidate| &candidate.name == mixin)
                    .with_context(|| format!("no mixin called `{mixin}`"))?;
                flatten(file, &mixin.items, plain, media, depth + 1)?;
            }
            Item::Media { query, items, .. } => {
                let mut inner = Vec::new();
                let mut deeper = Vec::new();
                flatten(file, items, &mut inner, &mut deeper, depth + 1)?;
                if !deeper.is_empty() {
                    bail!("a media block inside another is not supported");
                }
                media.push((query.clone(), inner));
            }
        }
    }
    Ok(())
}

/// A media query with each `$token` written as its value: a variable does not work in a query.
fn resolve_query(file: &ThemeFile, query: &str) -> anyhow::Result<String> {
    let mut resolved = query.to_owned();
    for name in references(query) {
        let value = file
            .token(&name)
            .and_then(|token| token.same.as_deref())
            .filter(|value| !value.contains('$'))
            .with_context(|| {
                format!("`${name}` in a media query must be a token with a plain value")
            })?;
        resolved = resolved.replace(&format!("${name}"), value);
    }
    Ok(resolved)
}

// ───────────── TypeScript ─────────────

fn quoted(names: impl Iterator<Item = String>) -> String {
    names
        .map(|name| format!("\"{name}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `field.label` as `fieldLabel`.
fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in name.chars() {
        if c == '.' || c == '-' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn typescript(file: &ThemeFile) -> anyhow::Result<String> {
    let mut out = format!("// {GENERATED_BY}\n");
    let _ = write!(
        out,
        "\nexport const themeIds = [{}] as const;\nexport type ThemeId = (typeof themeIds)[number];\n",
        quoted(file.themes.iter().map(|theme| theme.name.clone()))
    );
    let _ = write!(
        out,
        "\nexport const defaultLightTheme: ThemeId = \"{}\";\nexport const defaultDarkTheme: ThemeId = \"{}\";\n",
        file.default_light, file.default_dark
    );
    let ids_of_kind = |kind: &str| {
        quoted(
            file.themes
                .iter()
                .filter(|theme| theme.kind == kind)
                .map(|theme| theme.name.clone()),
        )
    };
    let _ = write!(
        out,
        "\nexport const lightThemeIds = [{}] as const;\nexport const darkThemeIds = [{}] as const;\n",
        ids_of_kind("light"),
        ids_of_kind("dark")
    );
    out.push_str("\n/** Where the layout changes, in pixels (the `bp-*` tokens). */\nexport const breakpoints = {\n");
    for token in &file.tokens {
        if let (Some(name), Some(value)) = (token.name.strip_prefix("bp-"), &token.same) {
            let _ = writeln!(out, "  {name}: {},", value.trim_end_matches("px"));
        }
    }
    out.push_str("} as const;\n");
    out.push_str("\n/** The choices that change token values: the attribute on <html> and its value. */\nexport const variants = {\n");
    for variant in &file.variants {
        // The formatter writes a key without quotes when it is a plain name.
        let key = if variant.name.contains('-') {
            format!("\"{}\"", variant.name)
        } else {
            variant.name.clone()
        };
        let _ = writeln!(
            out,
            "  {key}: {{ attribute: \"{}\", value: \"{}\" }},",
            variant.attribute, variant.value
        );
    }
    out.push_str("} as const;\n");
    out.push_str("\nexport const colorTokens = [\n");
    for color in file.colors() {
        let _ = writeln!(out, "  \"{}\",", color.name);
    }
    out.push_str("] as const;\nexport type ColorToken = (typeof colorTokens)[number];\n");
    out.push_str("\n/** Every token of the theme file: the CSS variable is `--` and the name. */\nexport const tokenNames = [\n");
    for token in &file.tokens {
        let _ = writeln!(out, "  \"{}\",", token.name);
    }
    out.push_str("] as const;\nexport type TokenName = (typeof tokenNames)[number];\n");
    out.push_str("\n/** The parts the theme file styles: what a component puts in `data-part`. */\nexport const part = {\n");
    let mut keys: Vec<String> = Vec::new();
    for name in file.part_names() {
        let key = camel(&name);
        if keys.contains(&key) {
            bail!("the parts `{name}` and another one are both called `{key}` in TypeScript");
        }
        let _ = writeln!(out, "  {key}: \"{name}\",");
        keys.push(key);
    }
    out.push_str("} as const;\nexport type PartName = (typeof part)[keyof typeof part];\n");
    out.push_str("\n/** The words of `data-variant` and `data-state` that the theme file styles, by part. */\nexport const partWords = {\n");
    for words in file.part_words() {
        let key = if words.part.contains(['.', '-']) {
            format!("\"{}\"", words.part)
        } else {
            words.part.clone()
        };
        let list = |names: &[String]| quoted(names.iter().cloned());
        let _ = writeln!(
            out,
            "  {key}: {{ variant: [{}], state: [{}] }},",
            list(&words.variants),
            list(&words.states)
        );
    }
    out.push_str("} as const;\n");
    Ok(out)
}

// ───────────── Rust ─────────────

/// `daylight` as the message `THEME_DAYLIGHT`.
fn message_of(theme: &str) -> String {
    format!("THEME_{}", theme.to_ascii_uppercase().replace('-', "_"))
}

fn rust(file: &ThemeFile) -> String {
    let mut out = format!("//! {GENERATED_BY}\n");
    out.push_str(
        "//!\n//! The themes of the settings *Light theme* and *Dark theme*, and the two that start. The\n//! theme file is the one place that lists the themes (ADR-0026).\n\nuse super::Choice;\nuse crate::message;\n",
    );
    for (kind, constant) in [("light", "LIGHT"), ("dark", "DARK")] {
        let _ = write!(
            out,
            "\n/// The {kind} themes, in the order of the theme file.\npub(super) const {constant}_THEME_CHOICES: &[Choice] = &[\n"
        );
        for theme in file.themes.iter().filter(|theme| theme.kind == kind) {
            let _ = writeln!(
                out,
                "    Choice::new(\"{}\", message::{}),",
                theme.name,
                message_of(&theme.name)
            );
        }
        out.push_str("];\n");
    }
    let _ = write!(
        out,
        "\n/// The light theme that starts.\npub(super) const DEFAULT_LIGHT_THEME: &str = \"{}\";\n\n/// The dark theme that starts.\npub(super) const DEFAULT_DARK_THEME: &str = \"{}\";\n",
        file.default_light, file.default_dark
    );
    out
}

