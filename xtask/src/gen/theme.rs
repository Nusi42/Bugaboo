    fn an_unknown_token_or_mixin_is_refused() {
        let text =
            std::fs::read_to_string(Repo::discover().unwrap().path("design/theme.kdl")).unwrap();
        for extra in [
            "\npart \"zz\" {\n  color \"$nope\"\n}\n",
            "\npart \"zz\" {\n  use \"nope\"\n}\n",
        ] {
            assert!(
                ThemeFile::parse(&format!("{text}{extra}")).is_err(),
                "{extra}"
            );
        }
    }
