//! `cargo xtask gen search-reader`: the Rust code that reads a tree and the readable fields of
//! `bb-searchlang` from JSON, written from their own definitions (coding-standards section 1).
//!
//! The browser gives the tree that Simple search edited to the WebAssembly module as JSON.
//! Deriving `Deserialize` for these types makes the module bigger than its budget (ADR-0005,
//! amendment M5, decision 7), and a reader written by hand would be a second definition of the
//! shape of the tree. So the reader is made from the types, with the same `syn` reading of the
//! source that writes the TypeScript types (`ts_types.rs`): one definition, two readers of it.
//! DOC-GENERATED fails when the file is not what the types give.
//!
//! What is understood: structs with named fields, enums of plain variants, and enums with a
//! `#[serde(tag = "…")]` whose variants have named fields or none; `String`, the integers, `bool`,
//! `Option`, `Vec` and `Box`; another type of the source. Anything else is an error that names the
//! type, so a new shape is never read wrongly in silence.

use std::fmt::Write as _;

use anyhow::{Context as _, bail};
use syn::{Fields, Item, Type};

use super::Generated;
use super::messages_rust::format;
use super::ts_types::{is_serde_type, serde_of, snake_case, variant_word};
use crate::repo::Repo;
use crate::source::read_text;

/// The generated file, relative to the repository root.
pub(crate) const OUTPUT: &str = "crates/bb-searchlang/src/browser/reader.generated.rs";
/// The Rust files it is made from: the types that come in, in the order they are read.
pub(crate) const INPUTS: [&str; 3] = [
    "crates/bb-searchlang/src/span.rs",
    "crates/bb-searchlang/src/syntax.rs",
    "crates/bb-searchlang/src/fields.rs",
];

/// The code that every reader uses. It reads a `serde_json::Value`, which is cheap in the module,
/// and says in plain words what is wrong.
const HELPERS: &str = r#"//! Generated by `cargo xtask gen search-reader` from the types of the tree. Do not edit by hand.

use serde_json::{Map, Value as Json};

pub(super) type Read<T> = Result<T, String>;

fn object<'a>(json: &'a Json, what: &str) -> Read<&'a Map<String, Json>> {
    json.as_object()
        .ok_or_else(|| format!("{what} is not an object"))
}

fn member<'a>(of: &'a Map<String, Json>, key: &str) -> Read<&'a Json> {
    of.get(key).ok_or_else(|| format!("`{key}` is missing"))
}

fn word(json: &Json) -> Read<&str> {
    json.as_str().ok_or_else(|| "a text is expected".to_owned())
}

fn text(json: &Json) -> Read<String> {
    word(json).map(str::to_owned)
}

fn integer<T: TryFrom<i64>>(json: &Json) -> Read<T> {
    json.as_i64()
        .and_then(|number| T::try_from(number).ok())
        .ok_or_else(|| "a whole number in range is expected".to_owned())
}

fn option<T>(json: &Json, read: impl Fn(&Json) -> Read<T>) -> Read<Option<T>> {
    if json.is_null() {
        Ok(None)
    } else {
        read(json).map(Some)
    }
}

fn list<T>(json: &Json, read: impl Fn(&Json) -> Read<T>) -> Read<Vec<T>> {
    json.as_array()
        .ok_or_else(|| "a list is expected".to_owned())?
        .iter()
        .map(read)
        .collect()
}

fn boxed<T>(json: &Json, read: impl Fn(&Json) -> Read<T>) -> Read<Box<T>> {
    read(json).map(Box::new)
}

fn unknown<T>(what: &str, found: &str) -> Read<T> {
    Err(format!("`{found}` is not a {what}"))
}

"#;

/// The helpers that only some sources need; a helper that nothing calls would be dead code.
const BOOLEAN: &str = r#"fn boolean(json: &Json) -> Read<bool> {
    json.as_bool()
        .ok_or_else(|| "true or false is expected".to_owned())
}

"#;

/// How a type is read.
enum Shape {
    Text,
    Integer,
    Boolean,
    Option(Box<Shape>),
    List(Box<Shape>),
    Boxed(Box<Shape>),
    Named(String),
}

fn shape(ty: &Type) -> anyhow::Result<Shape> {
    let Type::Path(path) = ty else {
        bail!("a type that is not a plain name cannot be read");
    };
    let segment = path.path.segments.last().context("an empty type")?;
    let name = segment.ident.to_string();
    let inner = || -> anyhow::Result<Box<Shape>> {
        let syn::PathArguments::AngleBracketed(arguments) = &segment.arguments else {
            bail!("`{name}` needs one type argument");
        };
        match arguments.args.first() {
            Some(syn::GenericArgument::Type(inner)) => Ok(Box::new(shape(inner)?)),
            _ => bail!("`{name}` needs one type argument"),
        }
    };
    Ok(match name.as_str() {
        "String" => Shape::Text,
        "bool" => Shape::Boolean,
        "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "usize" => Shape::Integer,
        "Option" => Shape::Option(inner()?),
        "Vec" => Shape::List(inner()?),
        "Box" => Shape::Boxed(inner()?),
        _ => Shape::Named(name),
    })
}

/// The reader of a shape, as something that takes `&Json`: a function name or a closure.
fn reader(shape: &Shape) -> String {
    match shape {
        Shape::Text => "text".to_owned(),
        Shape::Integer => "integer".to_owned(),
        Shape::Boolean => "boolean".to_owned(),
        Shape::Named(name) => function_name(name),
        Shape::Option(inner) => format!("|json| option(json, {})", reader(inner)),
        Shape::List(inner) => format!("|json| list(json, {})", reader(inner)),
        Shape::Boxed(inner) => format!("|json| boxed(json, {})", reader(inner)),
    }
}

/// The code that reads `json` (an expression of type `&Json`) as the shape.
fn read(shape: &Shape, json: &str) -> String {
    match shape {
        Shape::Option(inner) => format!("option({json}, {})?", reader(inner)),
        Shape::List(inner) => format!("list({json}, {})?", reader(inner)),
        Shape::Boxed(inner) => format!("boxed({json}, {})?", reader(inner)),
        leaf => format!("{}({json})?", reader(leaf)),
    }
}

fn function_name(type_name: &str) -> String {
    format!("read_{}", snake_case(type_name))
}

/// The members of a struct or of a variant, read from `object`; and whether one is a `bool`.
fn members(fields: &syn::FieldsNamed, object: &str) -> anyhow::Result<(String, bool)> {
    let mut out = String::new();
    let mut boolean = false;
    for field in &fields.named {
        let ident = field.ident.as_ref().context("a field without a name")?;
        let serde = serde_of(&field.attrs)?;
        if serde.default || serde.skip_serializing_if {
            bail!(
                "the field `{ident}`: `default` and `skip_serializing_if` are not understood by the reader; every member is read"
            );
        }
        let key = serde.rename.unwrap_or_else(|| ident.to_string());
        let shape = shape(&field.ty)?;
        boolean |= matches!(shape, Shape::Boolean);
        let code = read(&shape, &format!("member({object}, {key:?})?"));
        let _ = writeln!(out, "{ident}: {code},");
    }
    Ok((out, boolean))
}

fn struct_reader(item: &syn::ItemStruct) -> anyhow::Result<(String, bool)> {
    let name = &item.ident;
    if serde_of(&item.attrs)?.rename_all.is_some() {
        bail!("`{name}`: `rename_all` on a struct is not understood; rename the fields");
    }
    let Fields::Named(fields) = &item.fields else {
        bail!("`{name}` is not a struct with named fields");
    };
    let (members, boolean) = members(fields, "object")?;
    Ok((
        format!(
            "pub(super) fn {}(json: &Json) -> Read<{name}> {{\n let object = object(json, \"{name}\")?;\n Ok({name} {{\n{members}}})\n}}\n\n",
            function_name(&name.to_string()),
        ),
        boolean,
    ))
}

fn enum_reader(item: &syn::ItemEnum) -> anyhow::Result<(String, bool)> {
    let name = &item.ident;
    let serde = serde_of(&item.attrs)?;
    if serde.untagged {
        bail!("`{name}`: `untagged` is not understood by the reader");
    }
    let tag = serde.tag;
    let mut arms = String::new();
    let mut boolean = false;
    for variant in &item.variants {
        let word = variant_word(item, variant)?;
        let ident = &variant.ident;
        let built = match (&variant.fields, &tag) {
            (Fields::Unit, _) => format!("{name}::{ident}"),
            (Fields::Named(fields), Some(_)) => {
                let (members, found) = members(fields, "object")?;
                boolean |= found;
                format!("{name}::{ident} {{\n{members}}}")
            }
            _ => bail!(
                "`{name}::{ident}` holds data that is not understood: use plain variants, or a tag with named fields"
            ),
        };
        let _ = writeln!(arms, "{word:?} => Ok({built}),");
    }
    let (head, subject) = match &tag {
        Some(tag) => (
            format!("let object = object(json, \"{name}\")?;\n"),
            format!("word(member(object, {tag:?})?)?"),
        ),
        None => (String::new(), "word(json)?".to_owned()),
    };
    Ok((
        format!(
            "pub(super) fn {}(json: &Json) -> Read<{name}> {{\n{head}match {subject} {{\n{arms}other => unknown(\"{name}\", other),\n}}\n}}\n\n",
            function_name(&name.to_string())
        ),
        boolean,
    ))
}

/// The source of the reader, before it is formatted. Each source is a module of the crate and its
/// text; the types the readers build are imported from the module that declares them.
fn reader_of(sources: &[(String, String)]) -> anyhow::Result<String> {
    let mut readers = String::new();
    let mut imports = String::new();
    let mut boolean = false;
    let mut count = 0;
    for (module, source) in sources {
        let file = syn::parse_file(source).context("it is not Rust")?;
        let mut declared = Vec::new();
        for item in &file.items {
            let (code, found, name) = match item {
                Item::Struct(item) if is_serde_type(&item.attrs) => {
                    let (code, found) = struct_reader(item)?;
                    (code, found, item.ident.to_string())
                }
                Item::Enum(item) if is_serde_type(&item.attrs) => {
                    let (code, found) = enum_reader(item)?;
                    (code, found, item.ident.to_string())
                }
                _ => continue,
            };
            readers.push_str(&code);
            declared.push(name);
            boolean |= found;
            count += 1;
        }
        if !declared.is_empty() {
            let _ = writeln!(imports, "use crate::{module}::{{{}}};", declared.join(", "));
        }
    }
    if count == 0 {
        bail!("it declares no type that is read as JSON");
    }
    let head = "use serde_json::{Map, Value as Json};
";
    let mut out = HELPERS.replacen(
        head,
        &format!(
            "{head}
{imports}"
        ),
        1,
    );
    if boolean {
        out.push_str(BOOLEAN);
    }
    out.push_str(&readers);
    Ok(out)
}

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    let mut sources = Vec::new();
    for path in INPUTS {
        let module = path
            .rsplit('/')
            .next()
            .and_then(|file| file.strip_suffix(".rs"))
            .with_context(|| format!("{path} is no Rust file"))?;
        sources.push((module.to_owned(), read_text(repo, path)?));
    }
    let text =
        reader_of(&sources).context("the types of bb-searchlang cannot be read from JSON")?;
    Ok(vec![Generated::new(OUTPUT, format(repo, &text)?)])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn one(source: &str) -> String {
        reader_of(&[("shapes".to_owned(), source.to_owned())]).unwrap_or_default()
    }

    fn refused(source: &str) -> bool {
        reader_of(&[("shapes".to_owned(), source.to_owned())]).is_err()
    }

    #[test]
    fn a_struct_reads_each_member_by_its_type() {
        let code = one(
            "#[derive(Serialize)] pub struct Row { pub a: String, pub b: Option<u8>, pub c: Vec<Other> }",
        );
        assert!(
            code.contains("pub(super) fn read_row(json: &Json) -> Read<Row>"),
            "{code}"
        );
        assert!(code.contains("a: text(member(object, \"a\")?)?,"), "{code}");
        assert!(
            code.contains("b: option(member(object, \"b\")?, integer)?,"),
            "{code}"
        );
        assert!(
            code.contains("c: list(member(object, \"c\")?, read_other)?,"),
            "{code}"
        );
    }

    #[test]
    fn the_types_are_imported_from_the_module_that_declares_them() {
        let code = one("#[derive(Serialize)] pub struct Row { pub a: String }");
        assert!(code.contains("use crate::shapes::{Row};"), "{code}");
    }

    #[test]
    fn plain_variants_are_read_by_their_words() {
        let code = one(
            "#[derive(Serialize)] #[serde(rename_all = \"snake_case\")] pub enum End { StillOpen, Done }",
        );
        assert!(
            code.contains("\"still_open\" => Ok(End::StillOpen),"),
            "{code}"
        );
        assert!(code.contains("other => unknown(\"End\", other),"), "{code}");
    }

    #[test]
    fn a_tagged_enum_reads_its_tag_first() {
        let code = one(
            "#[derive(Serialize)] #[serde(tag = \"type\", rename_all = \"snake_case\")] pub enum Node { Leaf { text: String }, Gap }",
        );
        assert!(
            code.contains("match word(member(object, \"type\")?)? {"),
            "{code}"
        );
        assert!(code.contains("\"leaf\" => Ok(Node::Leaf {"), "{code}");
        assert!(code.contains("\"gap\" => Ok(Node::Gap),"), "{code}");
    }

    #[test]
    fn a_shape_that_cannot_be_read_is_an_error() {
        assert!(
            refused("#[derive(Serialize)] pub enum E { A(u8) }"),
            "data without a tag"
        );
        assert!(
            refused("#[derive(Serialize)] pub struct S(u8);"),
            "a tuple struct"
        );
        assert!(
            refused("#[derive(Serialize)] pub struct S { #[serde(default)] pub a: u8 }"),
            "a default"
        );
        assert!(
            refused(
                "#[derive(Serialize)] pub struct S { #[serde(skip_serializing_if = \"x\")] pub a: Option<u8> }"
            ),
            "a member that is left out"
        );
        assert!(
            refused(
                "#[derive(Serialize)] #[serde(rename_all = \"snake_case\")] pub struct S { pub a: u8 }"
            ),
            "rename_all on a struct"
        );
        assert!(
            refused("#[derive(Serialize)] #[serde(untagged)] pub enum E { A { a: u8 } }"),
            "untagged"
        );
    }
}
