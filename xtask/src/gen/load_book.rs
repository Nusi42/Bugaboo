//! `cargo xtask gen load-book`: the TypeScript types of the book of a run, from its Rust types.
//!
//! The book (`crates/bb-load-check/src/book.rs`) is written by the driver of `cargo xtask load`
//! (TypeScript) and read by `bb-load-check` (Rust). Its shape is declared once, in Rust; the
//! driver gets `web/tooling/load/book.generated.ts` (coding-standards §1). xtask does not link the
//! product crates, so the Rust source is read with `syn`.
//!
//! The same code writes the types of the wording of `bb-core` (`word_types.rs`), so the input and
//! the output of `bb-wasm` in the browser cannot differ from the Rust structs.

use super::Generated;
use super::ts_types::generated_file;
use crate::repo::Repo;

/// The generated file, relative to the repository root.
pub(crate) const OUTPUT: &str = "web/tooling/load/book.generated.ts";
/// The Rust types it is made from.
const SOURCE: &str = "crates/bb-load-check/src/book.rs";
const HEADER: &str = "// Generated by `cargo xtask gen load-book`. Do not edit by hand.\n\n";

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    generated_file(repo, OUTPUT, SOURCE, HEADER)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generate::ts_types::types_under;

    #[test]
    fn the_book_of_the_run_can_be_written_as_types() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap();
        let source = std::fs::read_to_string(root.join(SOURCE)).unwrap();
        let text = types_under(&source, HEADER).unwrap();
        for name in ["Work", "Kept", "Seen", "DraftEnd", "Drafted", "Book"] {
            assert!(text.contains(name), "{name}: {text}");
        }
    }
}
