//! The Rust side of `cargo xtask gen messages`: constants and functions for the message keys in
//! `bb-core` (UX-07, M0-F01).
//!
//! A message without placeholders becomes a constant (`SERVER_NOT_FOUND`), a message with
//! placeholders becomes a function whose parameters are the placeholders, typed by what the
//! message expects (`server_port_busy(port)`). TXT-CATALOG finds uses of keys by these names, so
//! the naming rule lives here once.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::Write as _;
use std::process::{Command, Stdio};

use anyhow::{Context as _, bail};

use super::icu::{ArgKind, Placeholders, placeholders};
use crate::repo::Repo;

/// Where the generated Rust goes, relative to the repository root.
pub(crate) const OUTPUT: &str = "crates/bb-core/src/message/generated.rs";

/// The name a key has in Rust: `error.resource.not-found` becomes `error_resource_not_found`.
/// Constants use the upper-case spelling of the same name.
pub(crate) fn function_name(key: &str) -> String {
    key.chars()
        .map(|c| if c == '.' || c == '-' { '_' } else { c })
        .collect()
}

/// The constant name of a message without placeholders.
pub(crate) fn constant_name(key: &str) -> String {
    function_name(key).to_ascii_uppercase()
}

/// The text of `crates/bb-core/src/message/generated.rs`, formatted like `cargo fmt` would.
pub(crate) fn generate(repo: &Repo, messages: &[(String, String)]) -> anyhow::Result<String> {
    let mut sorted: Vec<(&String, &String)> = messages.iter().map(|(k, t)| (k, t)).collect();
    sorted.sort_by(|a, b| a.0.cmp(b.0));
    let mut names: BTreeMap<String, &str> = BTreeMap::new();
    let mut constants = String::new();
    let mut functions = String::new();
    let mut catalog = String::new();
    for (key, text) in &sorted {
        if let Some(other) = names.insert(function_name(key), key) {
            bail!(
                "`{key}` and `{other}` would both be called `{}` in Rust; rename one",
                function_name(key)
            );
        }
        let found = placeholders(text).map_err(|problem| anyhow::anyhow!("{key}: {problem}"))?;
        let _ = writeln!(catalog, "    ({key:?}, {text:?}),");
        if found.is_empty() {
            let _ = write!(
                constants,
                "\n/// The message `{key}`.\npub const {}: MessageKey = MessageKey::new({key:?});\n",
                constant_name(key)
            );
        } else {
            functions.push_str(&function(key, &found));
        }
    }
    let imports = if functions.is_empty() {
        "use super::MessageKey;"
    } else {
        "use super::{Message, MessageKey, Value};"
    };
    let source = format!(
        "//! Generated by `cargo xtask gen messages` from messages/en.json. Do not edit by hand.\n\n\
         {imports}\n{constants}{functions}\n\
         /// Every message, sorted by key.\npub(super) const CATALOG: &[(&str, &str)] = &[\n{catalog}];\n"
    );
    format(repo, &source)
}

fn function(key: &str, found: &Placeholders) -> String {
    let mut parameters = Vec::new();
    let mut values = Vec::new();
    for (name, kind) in found {
        let param = parameter_name(name);
        let (rust_type, value) = match kind {
            ArgKind::Text => (
                "impl std::fmt::Display",
                format!("Value::Text({param}.to_string())"),
            ),
            ArgKind::Select => ("&str", format!("Value::Text({param}.to_owned())")),
            ArgKind::Number => ("i64", format!("Value::Number({param})")),
            ArgKind::Date => ("jiff::Timestamp", format!("Value::Date({param})")),
        };
        parameters.push(format!("{param}: {rust_type}"));
        values.push(format!("({name:?}, {value})"));
    }
    format!(
        "\n/// The message `{key}`.\n#[must_use]\npub fn {}({}) -> Message {{\n    \
         Message::with_arguments(MessageKey::new({key:?}), vec![{}])\n}}\n",
        function_name(key),
        parameters.join(", "),
        values.join(", ")
    )
}

/// A placeholder name as a Rust parameter: `due-date` becomes `due_date`, and a Rust keyword
/// gets a trailing underscore.
fn parameter_name(name: &str) -> String {
    let plain: String = name
        .chars()
        .map(|c| if c == '-' { '_' } else { c })
        .collect();
    if matches!(
        plain.as_str(),
        "type" | "match" | "ref" | "self" | "fn" | "loop" | "in" | "mod" | "use"
    ) {
        format!("{plain}_")
    } else {
        plain
    }
}

/// Runs `rustfmt` over generated code, so the file passes FMT-RUST without a second step.
fn format(repo: &Repo, source: &str) -> anyhow::Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .current_dir(repo.root())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("could not run rustfmt; it is part of the pinned Rust toolchain")?;
    let mut stdin = child.stdin.take().context("rustfmt has no input")?;
    let input = source.to_owned();
    // Written from a thread so a large file cannot fill the pipe while rustfmt waits to write.
    let writer = std::thread::spawn(move || stdin.write_all(input.as_bytes()));
    let output = child.wait_with_output().context("rustfmt did not finish")?;
    writer
        .join()
        .map_err(|_| anyhow::anyhow!("the rustfmt input thread stopped"))?
        .context("could not give the code to rustfmt")?;
    if !output.status.success() {
        bail!(
            "rustfmt rejected the generated code: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(crate::source::normalize(&String::from_utf8(output.stdout)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn create(messages: &[(&str, &str)]) -> anyhow::Result<String> {
        let owned: Vec<(String, String)> = messages
            .iter()
            .map(|(k, t)| ((*k).to_owned(), (*t).to_owned()))
            .collect();
        generate(&Repo::discover()?, &owned)
    }

    #[test]
    fn keys_become_constants_and_functions() {
        let code = create(&[
            ("a.b-c", "Plain"),
            ("a.count", "{n, plural, one {# item} other {# items}}"),
            ("a.hi", "Hi {name}"),
        ])
        .unwrap();
        assert!(
            code.contains("pub const A_B_C: MessageKey = MessageKey::new(\"a.b-c\");"),
            "{code}"
        );
        assert!(code.contains("pub fn a_count(n: i64) -> Message"), "{code}");
        assert!(
            code.contains("pub fn a_hi(name: impl std::fmt::Display) -> Message"),
            "{code}"
        );
        assert!(code.contains("(\"a.b-c\", \"Plain\"),"), "{code}");
    }

    #[test]
    fn names_that_collide_are_rejected() {
        assert!(create(&[("a-b.c", "x"), ("a.b-c", "y")]).is_err());
    }

    #[test]
    fn the_catalog_is_sorted_by_key() {
        let code = create(&[("b.x", "1"), ("a.y", "2")]).unwrap();
        assert!(code.find("\"a.y\"").unwrap() < code.find("\"b.x\"").unwrap());
    }

    #[test]
    fn names_follow_the_one_rule() {
        assert_eq!(
            function_name("error.resource.not-found"),
            "error_resource_not_found"
        );
        assert_eq!(
            constant_name("error.resource.not-found"),
            "ERROR_RESOURCE_NOT_FOUND"
        );
    }
}
