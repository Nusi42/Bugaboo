//! `cargo xtask gen clippy`: the `clippy.toml` of the crates that do no I/O (ARCH-PURE).
//!
//! `bb-core`, `bb-searchlang` and `bb-markdown` are also built for WebAssembly, so they must not
//! reach the file system, the network, the clock, the environment, a thread or a process. Clippy
//! checks that with `disallowed-methods` and `disallowed-types`, but it reads only the nearest
//! `clippy.toml`, so each of these crates has a file of its own. They are written here, from the
//! root `clippy.toml` (the settings of every crate) and the one list below (what reaches the
//! world), so no file is edited by hand and no two can differ.

use std::fmt::Write as _;

use anyhow::Context as _;

use super::Generated;
use crate::repo::Repo;
use crate::source::read_text;

/// The settings every crate has.
const ROOT_CONFIG: &str = "clippy.toml";

/// A crate that does no I/O, with where its clippy file is and what only it needs besides the list
/// of the standard library.
pub(crate) struct PureCrate {
    pub(crate) name: &'static str,
    config: &'static str,
    /// Methods of its own dependencies that read the world, such as the clock of a date library.
    extra_methods: &'static [(&'static str, &'static str)],
}

/// The crates that do no I/O.
pub(crate) const PURE_CRATES: [PureCrate; 3] = [
    PureCrate {
        name: "bb-core",
        config: "crates/bb-core/clippy.toml",
        extra_methods: &[("jiff::Timestamp::now", CLOCK), ("jiff::Zoned::now", CLOCK)],
    },
    PureCrate {
        name: "bb-searchlang",
        config: "crates/bb-searchlang/clippy.toml",
        extra_methods: &[],
    },
    PureCrate {
        name: "bb-markdown",
        config: "crates/bb-markdown/clippy.toml",
        extra_methods: &[],
    },
];

const FILES: &str = "the file system";
const ENVIRONMENT: &str = "the environment";
const CLOCK: &str = "the clock";
const SCREEN: &str = "the screen or the keyboard";
const THREADS: &str = "threads and processes";
const NETWORK: &str = "the network";

/// The methods of the standard library that reach the world, and what each reaches.
const METHODS: [(&str, &str); 29] = [
    ("std::fs::read", FILES),
    ("std::fs::read_to_string", FILES),
    ("std::fs::write", FILES),
    ("std::fs::read_dir", FILES),
    ("std::fs::create_dir", FILES),
    ("std::fs::create_dir_all", FILES),
    ("std::fs::remove_file", FILES),
    ("std::fs::remove_dir", FILES),
    ("std::fs::remove_dir_all", FILES),
    ("std::fs::rename", FILES),
    ("std::fs::copy", FILES),
    ("std::fs::metadata", FILES),
    ("std::fs::canonicalize", FILES),
    ("std::path::Path::exists", FILES),
    ("std::path::Path::is_file", FILES),
    ("std::path::Path::is_dir", FILES),
    ("std::env::var", ENVIRONMENT),
    ("std::env::var_os", ENVIRONMENT),
    ("std::env::vars", ENVIRONMENT),
    ("std::env::args", ENVIRONMENT),
    ("std::env::current_dir", ENVIRONMENT),
    ("std::process::exit", THREADS),
    ("std::thread::spawn", THREADS),
    ("std::thread::sleep", THREADS),
    ("std::time::SystemTime::now", CLOCK),
    ("std::time::Instant::now", CLOCK),
    ("std::io::stdin", SCREEN),
    ("std::io::stdout", SCREEN),
    ("std::io::stderr", SCREEN),
];

/// The types of the standard library that reach the world.
const TYPES: [(&str, &str); 7] = [
    ("std::fs::File", FILES),
    ("std::fs::OpenOptions", FILES),
    ("std::process::Command", THREADS),
    ("std::net::TcpStream", NETWORK),
    ("std::net::TcpListener", NETWORK),
    ("std::net::UdpSocket", NETWORK),
    ("std::thread::JoinHandle", THREADS),
];

/// The paths this generator writes.
pub(crate) fn output_paths() -> Vec<&'static str> {
    PURE_CRATES.iter().map(|pure| pure.config).collect()
}

fn entries(key: &str, list: &[(&str, &str)]) -> String {
    let mut text = format!("{key} = [\n");
    for (path, world) in list {
        let _ = writeln!(
            text,
            "  {{ path = \"{path}\", reason = \"ARCH-PURE: this crate does no I/O and never reaches {world}; the caller passes it in\" }},"
        );
    }
    text.push_str("]\n");
    text
}

pub(crate) fn generate(repo: &Repo) -> anyhow::Result<Vec<Generated>> {
    let root =
        read_text(repo, ROOT_CONFIG).with_context(|| format!("could not read {ROOT_CONFIG}"))?;
    Ok(PURE_CRATES
        .iter()
        .map(|pure| {
            let methods: Vec<(&str, &str)> = METHODS
                .iter()
                .chain(pure.extra_methods)
                .copied()
                .collect();
            Generated::new(
                pure.config,
                format!(
                    "# Generated by `cargo xtask gen clippy` from {ROOT_CONFIG} and the list of what reaches the world.\n# Do not edit by hand. Clippy reads only the nearest clippy.toml, so the settings of {ROOT_CONFIG} are\n# repeated, then comes what ARCH-PURE (architecture section 4, rule 1) disallows in this crate.\n\n{}\n{}{}",
                    root.trim_end(),
                    entries("disallowed-methods", &methods),
                    entries("disallowed-types", &TYPES),
                ),
            )
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_crate_gets_the_list_and_its_own_extras() {
        let repo = Repo::discover().unwrap();
        let files = generate(&repo).unwrap();
        assert_eq!(files.len(), PURE_CRATES.len());
        let core = files.iter().find(|f| f.path.contains("bb-core")).unwrap();
        let markdown = files
            .iter()
            .find(|f| f.path.contains("bb-markdown"))
            .unwrap();
        assert!(core.content.contains("jiff::Zoned::now"));
        assert!(!markdown.content.contains("jiff"));
        assert!(markdown.content.contains("std::fs::read_to_string"));
        assert!(markdown.content.starts_with("# Generated by"));
    }
}
